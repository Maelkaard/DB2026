DROP SCHEMA IF EXISTS sem6 CASCADE;
CREATE SCHEMA sem6;

CREATE TABLE sem6.products (
    product_id INT PRIMARY KEY,
    product_name TEXT NOT NULL,
    category TEXT NOT NULL,
    base_price NUMERIC(10, 2) NOT NULL CHECK (base_price > 0)
);

CREATE TABLE sem6.customers (
    customer_id INT PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    city TEXT NOT NULL
);

CREATE TABLE sem6.orders (
    order_id INT PRIMARY KEY,
    customer_id INT NOT NULL REFERENCES sem6.customers(customer_id),
    order_date DATE NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('new', 'paid', 'shipped', 'canceled')),
    region TEXT NOT NULL
);

CREATE TABLE sem6.order_items (
    order_item_id INT PRIMARY KEY,
    order_id INT NOT NULL REFERENCES sem6.orders(order_id),
    product_id INT NOT NULL REFERENCES sem6.products(product_id),
    quantity INT NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price > 0)
);

CREATE TABLE sem6.parts (
    part TEXT NOT NULL,
    sub_part TEXT NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (part, sub_part)
);

CREATE TABLE sem6.employees (
    employee_id INT PRIMARY KEY,
    full_name TEXT NOT NULL,
    manager_id INT REFERENCES sem6.employees(employee_id),
    department TEXT NOT NULL,
    salary NUMERIC(10, 2) NOT NULL CHECK (salary > 0)
);

