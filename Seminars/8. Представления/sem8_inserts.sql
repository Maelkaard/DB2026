DROP SCHEMA sem8 CASCADE;

CREATE SCHEMA sem8;

CREATE TABLE sem8.reader (
    reader_id        INTEGER PRIMARY KEY,
    full_name        TEXT NOT NULL,
    registration_dt  DATE NOT NULL
);

CREATE TABLE sem8.book (
    book_id          INTEGER PRIMARY KEY,
    title            TEXT NOT NULL,
    author_name      TEXT NOT NULL,
    genre_name       TEXT NOT NULL,
    publish_year     INTEGER NOT NULL
);

CREATE TABLE sem8.book_copy (
    copy_id          INTEGER PRIMARY KEY,
    book_id          INTEGER NOT NULL REFERENCES sem8.book(book_id),
    inventory_code   TEXT NOT NULL UNIQUE,
    shelf_code       TEXT NOT NULL,
    status           TEXT NOT NULL CHECK (status IN ('available', 'loaned', 'repair', 'lost'))
);

CREATE TABLE sem8.loan (
    loan_id          INTEGER PRIMARY KEY,
    copy_id          INTEGER NOT NULL REFERENCES sem8.book_copy(copy_id),
    reader_id        INTEGER NOT NULL REFERENCES sem8.reader(reader_id),
    loan_dt          DATE NOT NULL,
    due_dt           DATE NOT NULL,
    return_dt        DATE
);

